package com.comp2042.game.events;

/**
 * Enumerated the types of movement or action events that can occur in the game.
 * <p>
 *     These types are used to categorize user inputs and game logic triggers
 *     for processing by the event dispatcher.
 * </p>
 */
public enum EventType {
    DOWN, LEFT, RIGHT, ROTATE, DROP, HOLD
}
